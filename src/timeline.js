// Shared timeline: the single source of truth for scene timing, used by the
// renderer, the audio engine, the preview UI and the QC tools.
import { SCENES } from './scenes/index.js';

export function resolveTimeline(project) {
  const scenes = [];
  let t = 0;
  project.scenes.forEach((s, i) => {
    if (s.enabled === false) return;
    const dur = Math.max(0.2, Number(s.duration) || 0);
    scenes.push({ ...s, index: scenes.length, sourceIndex: i, start: t, end: t + dur, dur });
    t += dur;
  });
  scenes.forEach((s, i) => {
    s.prev = scenes[i - 1]?.type ?? null;
    s.next = scenes[i + 1]?.type ?? null;
  });
  return { scenes, total: t, fps: project.meta.fps };
}

export function sceneAt(tl, t) {
  const { scenes } = tl;
  for (const s of scenes) if (t < s.end) return s;
  return scenes[scenes.length - 1];
}

/** All audio/visual cues in absolute time, generated by each scene module from its own keyframes. */
export function collectCues(project, tl = resolveTimeline(project)) {
  const out = [];
  for (const s of tl.scenes) {
    const mod = SCENES[s.type];
    if (!mod?.cues) continue;
    for (const c of mod.cues(s, project, s.dur)) {
      if (c.t < 0 || c.t > s.dur + 1e-6) continue;
      out.push({ ...c, scene: s.id, local: c.t, t: s.start + c.t });
    }
  }
  return out.sort((a, b) => a.t - b.t);
}

/** Text hold windows (absolute) so QC can check readability after timing edits. */
export function collectHolds(project, tl = resolveTimeline(project)) {
  const out = [];
  for (const s of tl.scenes) {
    const mod = SCENES[s.type];
    if (!mod?.holds) continue;
    for (const h of mod.holds(s, project, s.dur)) if (!h.layer || s.layers?.[h.layer]?.visible !== false) out.push({ ...h, scene: s.id, start: s.start + h.start, end: s.start + h.end });
  }
  return out;
}
